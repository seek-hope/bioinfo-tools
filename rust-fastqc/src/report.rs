//! Report assembly and emission.
//!
//! Produces `fastqc_data.txt` byte for byte in FastQC 0.13.0's layout, plus
//! `summary.txt`, a data-table HTML report and a stored ZIP bundle. Plot images
//! are not fabricated; the HTML states that explicitly.

use crate::modules::{all_modules, ModuleResult};
use crate::stats::QcStats;
use crate::HEADER;

/// A complete QC report for one input file.
pub struct Report {
    /// The module results, in FastQC's order.
    pub modules: Vec<ModuleResult>,
}

impl Report {
    /// Build a report from accumulated statistics.
    pub fn from_stats(stats: &QcStats) -> Report {
        Report {
            modules: all_modules(stats),
        }
    }

    /// Render the whole `fastqc_data.txt`.
    ///
    /// The layout is: the `##FastQC` version line, then each module block, with no
    /// blank lines between blocks. FastQC ends the file with the final
    /// `>>END_MODULE` line and a newline.
    pub fn render(&self) -> String {
        let mut out = String::new();
        out.push_str(HEADER);
        out.push('\n');
        for module in &self.modules {
            out.push_str(&module.render());
        }
        out
    }

    /// The module names in report order.
    pub fn module_names(&self) -> Vec<&'static str> {
        self.modules.iter().map(|module| module.name).collect()
    }

    /// Render FastQC's `summary.txt`: `STATUS<TAB>module<TAB>filename`.
    pub fn render_summary(&self, filename: &str) -> String {
        let mut out = String::new();
        for module in &self.modules {
            out.push_str(&format!(
                "{}\t{}\t{}\n",
                module.status.as_str().to_ascii_uppercase(),
                module.name,
                filename
            ));
        }
        out
    }

    /// Render a self-contained HTML report with the module tables.
    ///
    /// FastQC's HTML embeds PNG plots. This report instead contains the module
    /// tables and states that plot images are unavailable.
    pub fn render_html(&self, filename: &str) -> String {
        let mut out = String::new();
        out.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
        out.push_str(&format!(
            "<title>FastQC Report: {}</title>\n",
            escape_html(filename)
        ));
        out.push_str("<style>body{font-family:sans-serif;margin:2em}table{border-collapse:collapse}th,td{border:1px solid #888;padding:.25em .5em;text-align:left}pre{background:#f6f6f6;padding:.75em;overflow:auto}.pass{color:#070}.warn{color:#a60}.fail{color:#b00}</style>\n");
        out.push_str("</head>\n<body>\n<h1>FastQC Report</h1>\n");
        out.push_str(&format!(
            "<p>Input: <code>{}</code></p>\n<p>Generated by rust-fastqc; plot images are not emitted.</p>\n<h2>Summary</h2>\n<table><thead><tr><th>Status</th><th>Module</th></tr></thead><tbody>\n",
            escape_html(filename)
        ));
        for module in &self.modules {
            let status = module.status.as_str();
            out.push_str(&format!(
                "<tr><td class=\"{}\">{}</td><td>{}</td></tr>\n",
                status,
                status.to_ascii_uppercase(),
                escape_html(module.name)
            ));
        }
        out.push_str("</tbody></table>\n");
        for module in &self.modules {
            out.push_str(&format!(
                "<h2>{}</h2>\n<p>Status: <span class=\"{}\">{}</span></p>\n<pre>",
                escape_html(module.name),
                module.status.as_str(),
                module.status.as_str().to_ascii_uppercase()
            ));
            for line in &module.lines {
                out.push_str(&escape_html(line));
                out.push('\n');
            }
            out.push_str("</pre>\n");
        }
        out.push_str("</body>\n</html>\n");
        out
    }
}

fn escape_html(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for character in text.chars() {
        match character {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            other => out.push(other),
        }
    }
    out
}

/// Writes a report to a path, creating parent directories.
pub struct ReportWriter;

impl ReportWriter {
    /// Write `report` to `path`.
    pub fn write(report: &Report, path: &std::path::Path) -> crate::error::Result<()> {
        if let Some(parent) = path.parent() {
            if !parent.as_os_str().is_empty() {
                std::fs::create_dir_all(parent).map_err(|error| {
                    crate::error::Error::io(format!("{}: {error}", parent.display()))
                })?;
            }
        }
        std::fs::write(path, report.render())
            .map_err(|error| crate::error::Error::io(format!("{}: {error}", path.display())))
    }

    /// Write FastQC-style report artifacts.
    ///
    /// `data_path` is `<sample>_fastqc/fastqc_data.txt`; the sibling
    /// `<sample>_fastqc.html` and, unless deleted, `<sample>_fastqc.zip` are
    /// created next to that directory. The directory itself is written only
    /// when `extract` is true. `delete` has an effect only with `extract`.
    pub fn write_bundle(
        report: &Report,
        data_path: &std::path::Path,
        filename: &str,
        extract: bool,
        delete: bool,
    ) -> crate::error::Result<()> {
        let dir = data_path.parent().ok_or_else(|| {
            crate::error::Error::io(format!("{}: missing parent directory", data_path.display()))
        })?;
        let root = dir
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .ok_or_else(|| crate::error::Error::io("report directory has no name".to_string()))?;
        let summary = report.render_summary(filename);
        let html = report.render_html(filename);

        if extract {
            Self::write(report, data_path)?;
            std::fs::write(dir.join("summary.txt"), &summary)
                .map_err(|error| crate::error::Error::io(format!("{}: {error}", dir.display())))?;
            std::fs::write(dir.join("fastqc_report.html"), &html)
                .map_err(|error| crate::error::Error::io(format!("{}: {error}", dir.display())))?;
        }
        std::fs::write(dir.with_extension("html"), &html)
            .map_err(|error| crate::error::Error::io(format!("{}: {error}", dir.display())))?;

        let zip_path = dir.with_extension("zip");
        if extract && delete {
            match std::fs::remove_file(&zip_path) {
                Ok(()) => {}
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => {
                    return Err(crate::error::Error::io(format!(
                        "{}: {error}",
                        zip_path.display()
                    )))
                }
            }
        } else {
            let entries = vec![
                (
                    format!("{root}/fastqc_data.txt"),
                    report.render().into_bytes(),
                ),
                (format!("{root}/summary.txt"), summary.into_bytes()),
                (format!("{root}/fastqc_report.html"), html.into_bytes()),
            ];
            crate::zip::write_stored_zip(&zip_path, &entries)?;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_report_starts_with_the_fastqc_version_line() {
        let stats = QcStats::new("x.fq");
        let report = Report::from_stats(&stats);
        let text = report.render();
        assert!(text.starts_with("##FastQC\t0.13.0\n"), "{text}");
    }

    #[test]
    fn every_module_block_is_terminated() {
        let stats = QcStats::new("x.fq");
        let report = Report::from_stats(&stats);
        let text = report.render();
        let opens = text.matches(">>").count();
        let ends = text.matches(">>END_MODULE").count();
        // Each module contributes one opening '>>' plus one '>>END_MODULE'.
        assert_eq!(ends, report.modules.len());
        assert_eq!(opens, report.modules.len() * 2);
    }

    #[test]
    fn summary_and_html_include_every_module() {
        let stats = QcStats::new("x.fq");
        let report = Report::from_stats(&stats);
        let summary = report.render_summary("x.fq");
        let html = report.render_html("x.fq");
        for module in &report.modules {
            assert!(summary.contains(module.name), "{summary}");
            assert!(html.contains(module.name), "{html}");
        }
        assert!(summary.contains("\tBasic Statistics\tx.fq\n"));
        assert!(html.contains("<!DOCTYPE html>"));
        assert!(html.contains("plot images are not emitted"));
    }

    #[test]
    fn modules_appear_in_fastqc_order() {
        let mut stats = QcStats::new("x.fq");
        // Quality modules are present only when some quality was observed.
        stats.add_read(b"ACGT", b"5555", 33);
        let report = Report::from_stats(&stats);
        assert_eq!(
            report.module_names(),
            vec![
                "Basic Statistics",
                "Per base sequence quality",
                "Per sequence quality scores",
                "Per base sequence content",
                // GC content precedes N content in FastQC's report order.
                "Per sequence GC content",
                "Per base N content",
                "Sequence Length Distribution",
                "Sequence Duplication Levels",
                "Overrepresented sequences",
                "Adapter Content",
            ]
        );
    }
}
